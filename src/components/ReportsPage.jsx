import { useMemo, useState } from 'react'
import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import { Download, FileText } from 'lucide-react'

const toIsoDate = (date) => date.toISOString().slice(0, 10)

function ReportsPage({ stocks, isSuperAdmin, roleLabel, generatedBy, currentUserId }) {
  const [reportType, setReportType] = useState('daily')
  const [fromDate, setFromDate] = useState(toIsoDate(new Date()))
  const [toDate, setToDate] = useState(toIsoDate(new Date()))
  const [farmerKey, setFarmerKey] = useState('')
  const [stockType, setStockType] = useState('all')
  const [message, setMessage] = useState('')

  const farmers = useMemo(() => {
    const map = new Map()
    stocks.forEach((stock) => {
      const key = `${stock.customerName}|${stock.customerPhone || ''}`
      if (!map.has(key)) map.set(key, { key, name: stock.customerName, phone: stock.customerPhone || '' })
    })
    return Array.from(map.values()).sort((a, b) => a.name.localeCompare(b.name))
  }, [stocks])

  const applyPreset = (type) => {
    setReportType(type)
    const now = new Date()
    const end = toIsoDate(now)
    let start = end
    if (type === 'weekly') {
      const date = new Date(now)
      date.setDate(date.getDate() - 6)
      start = toIsoDate(date)
    } else if (type === 'monthly') {
      start = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-01`
    }
    setFromDate(start)
    setToDate(end)
  }

  const generatePdf = () => {
    setMessage('')
    if (!fromDate || !toDate) {
      setMessage('Please select a valid date range.')
      return
    }
    if (fromDate > toDate) {
      setMessage('From Date cannot be after To Date.')
      return
    }

    let records = stocks.filter((stock) =>
      stock.stockDate >= fromDate && stock.stockDate <= toDate,
    )
    if (farmerKey) {
      const selected = farmers.find((farmer) => farmer.key === farmerKey)
      if (selected) {
        records = records.filter((stock) =>
          stock.customerName === selected.name &&
          (stock.customerPhone || '') === selected.phone,
        )
      }
    }
    if (stockType === 'in') {
      records = records.filter((stock) => !stock.stockReason && Number(stock.afterDryWeight) >= 0)
    } else if (stockType === 'out') {
      records = records.filter((stock) => Boolean(stock.stockReason) || Number(stock.afterDryWeight) < 0)
    }

    const typeTitles = {
      daily: 'Daily Stock Report',
      weekly: 'Weekly Stock Report',
      monthly: 'Monthly Stock Report',
      custom: 'Custom Date Range Report',
      farmer: 'Farmer-wise Stock Report',
      'stock-in': 'Stock In Report',
      'stock-out': 'Stock Out Report',
      complete: 'Complete Stock Report',
    }
    const title = typeTitles[reportType] || 'Stock Report'
    const totalStockAdded = records
      .filter((stock) => !stock.stockReason && Number(stock.afterDryWeight) >= 0)
      .reduce((sum, stock) => sum + Number(stock.afterDryWeight), 0)
    const totalStockRemoved = records
      .filter((stock) => Boolean(stock.stockReason) || Number(stock.afterDryWeight) < 0)
      .reduce((sum, stock) => sum + Math.abs(Number(stock.afterDryWeight)), 0)
    const balance = stocks
      .filter((stock) => stock.stockDate <= toDate)
      .reduce((sum, stock) =>
        sum + (stock.stockReason || Number(stock.afterDryWeight) < 0
          ? -Math.abs(Number(stock.afterDryWeight))
          : Number(stock.afterDryWeight)),
      0)

    const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' })
    const pageWidth = doc.internal.pageSize.getWidth()
    const generatedAt = new Date()
    const renderHeader = () => {
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(15)
      doc.setTextColor(15, 118, 110)
      doc.text('Gurusamy Cardamom Management System', pageWidth / 2, 32, { align: 'center' })
      doc.setTextColor(30, 41, 59)
      doc.setFontSize(11)
      doc.text(title, pageWidth / 2, 50, { align: 'center' })
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(9)
      doc.text(`Generated: ${generatedAt.toLocaleString()}`, 40, 68)
      doc.text(`Selected range: ${fromDate} to ${toDate}`, pageWidth - 40, 68, { align: 'right' })
    }
    const renderFooter = (data) => {
      const height = doc.internal.pageSize.getHeight()
      doc.setDrawColor(203, 213, 225)
      doc.line(40, height - 38, pageWidth - 40, height - 38)
      doc.setFontSize(8)
      doc.setTextColor(71, 85, 105)
      doc.text(`Generated By: ${generatedBy}`, 40, height - 23)
      doc.text(`Role: ${roleLabel}`, 220, height - 23)
      doc.text(`Timestamp: ${generatedAt.toISOString()}`, 350, height - 23)
      doc.text(`Page ${data.pageNumber}`, pageWidth - 40, height - 23, { align: 'right' })
    }

    renderHeader()
    doc.setFontSize(10)
    doc.setTextColor(30, 41, 59)
    doc.text(`Total Farmers: ${new Set(records.map((record) => record.customerName.toLowerCase())).size}`, 40, 92)
    doc.text(`Total Stock Added: ${totalStockAdded.toFixed(2)} KG`, 210, 92)
    doc.text(`Total Stock Removed: ${totalStockRemoved.toFixed(2)} KG`, 390, 92)
    doc.text(`Current Stock Balance: ${balance.toFixed(2)} KG`, 590, 92)

    const rows = records.map((record) => [
      new Date(`${record.stockDate}T00:00:00`).toLocaleDateString('en-GB'),
      record.customerName,
      Number(record.beforeDryWeight).toFixed(2),
      Number(record.afterDryWeight).toFixed(2),
    ])

    autoTable(doc, {
      startY: 108,
      head: [['Date', 'Farmer Name', 'Before Drying', 'After Drying']],
      body: rows,
      styles: { fontSize: 9, cellPadding: 6, overflow: 'linebreak' },
      headStyles: { fillColor: [15, 118, 110], textColor: [255, 255, 255] },
      alternateRowStyles: { fillColor: [240, 253, 250] },
      margin: { left: 40, right: 40, top: 82, bottom: 48 },
      didDrawPage: (data) => {
        if (data.pageNumber > 1) renderHeader()
        renderFooter(data)
      },
    })

    if (!rows.length) {
      doc.setFontSize(10)
      doc.text('No stock records found for the selected filters.', 40, 128)
    }

    const safeTitle = title.toLowerCase().replace(/[^a-z0-9]+/g, '-')
    doc.save(`${safeTitle}-${fromDate}-to-${toDate}.pdf`)
  }

  return (
    <section className="panel">
      <h2><FileText size={18} style={{ verticalAlign: 'middle', marginRight: 8 }} />Advanced PDF Reports</h2>
      <div className="filters-grid">
        <label>
          Report Type
          <select value={reportType} onChange={(event) => applyPreset(event.target.value)}>
            <option value="daily">Daily Stock Report</option>
            <option value="weekly">Weekly Stock Report</option>
            <option value="monthly">Monthly Stock Report</option>
            <option value="custom">Custom Date Range Report</option>
            <option value="farmer">Farmer-wise Stock Report</option>
            <option value="stock-in">Stock In Report</option>
            <option value="stock-out">Stock Out Report</option>
            {isSuperAdmin ? <option value="complete">Complete Stock Report</option> : null}
          </select>
        </label>
        <label>From Date<input type="date" value={fromDate} onChange={(event) => setFromDate(event.target.value)} /></label>
        <label>To Date<input type="date" value={toDate} onChange={(event) => setToDate(event.target.value)} /></label>
        <label>
          Farmer
          <select value={farmerKey} onChange={(event) => setFarmerKey(event.target.value)}>
            <option value="">All permitted farmers</option>
            {farmers.map((farmer) => (
              <option key={farmer.key} value={farmer.key}>{farmer.name} ({farmer.phone || '-'})</option>
            ))}
          </select>
        </label>
        <label>
          Stock Type
          <select value={stockType} onChange={(event) => setStockType(event.target.value)}>
            <option value="all">All Stock</option>
            <option value="in">Stock In</option>
            <option value="out">Stock Out</option>
          </select>
        </label>
      </div>
      <div className="actions">
        <button type="button" onClick={generatePdf}>
          <Download size={16} style={{ verticalAlign: 'middle', marginRight: 6 }} />
          Generate PDF
        </button>
      </div>
      {message ? <p className="auth-message">{message}</p> : null}
      <p className="permission-note">Reports use only records permitted for {roleLabel} account {currentUserId}.</p>
    </section>
  )
}

export default ReportsPage
